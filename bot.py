    if num_players >= 14:
        roles.append("bomber")
    if num_players >= 15:
        roles.append("arsonist")
    if num_players >= 16:
        roles.append("wolf")
    if num_players >= 18:
        roles.append("seer")
    
    # Fill rest with civilians
    while len(roles) < num_players:
        roles.append("civilian")
    
    random.shuffle(roles)
    return roles



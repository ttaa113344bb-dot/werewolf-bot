async def kick_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """يخلي صاحب اللعبة يطرد لاعب انضم غلط، بس قبل ما تبدي اللعبة (WAITING بس)."""
    user = update.effective_user
    chat_id = update.effective_chat.id

    target_game = None
    for gid, g in games.items():
        if g.phase == GamePhase.WAITING and g.chat_id == chat_id:
            target_game = g
            break

    if not target_game:
        await update.message.reply_text(MSG["no_game"])
        return

    if target_game.host_id != user.id:
        await update.message.reply_text("بس صاحب اللعبة يگدر يطرد لاعب.")
        return

    target_id = None
    if update.message.reply_to_message:
        target_id = update.message.reply_to_message.from_user.id
    elif context.args:
        name_query = " ".join(context.args).strip().lower()
        for uid, p in target_game.players.items():
            if p.name.lower() == name_query:
                target_id = uid
                break

    if not target_id or target_id not in target_game.players:
        await update.message.reply_text("رد على رسالة اللاعب أو اكتب اسمه بالضبط: /kick اسم_اللاعب")
        return

    if target_id == target_game.host_id:
        await update.message.reply_text("ما تگدر تطرد نفسك، استخدم /endgame إذا تريد تلغي اللعبة.")
        return

    kicked_name = target_game.players[target_id].name
    del target_game.players[target_id]
    user_games.pop(target_id, None)
    await update.message.reply_text(f"🚫 طردنا {kicked_name} من اللعبة. العدد هسة: {len(target_game.players)}")



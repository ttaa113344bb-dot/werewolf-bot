async def button_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Handle inline buttons with strict phase/role validation."""
    query = update.callback_query
    await query.answer()
    user = update.effective_user
    data = query.data or ""

    if user.id not in user_games or user_games[user.id] not in games:
        await query.edit_message_text("ماكو لعبة شغالة!")
        return

    game = games[user_games[user.id]]
    player = game.players.get(user.id)
    if not player:
        await query.edit_message_text("إنت مو داخل بهاللعبة!")
        return
    if not player.alive:
        await query.answer("إنت ميت يمعود، ما تگدر تسوي شي هسة 😂", show_alert=True)
        return

    if data.startswith("heal_"):
        if player.role != "healer" or game.phase != GamePhase.HEALER:
            await query.answer("هسة مو دور الحكيم.", show_alert=True)
            return
        target_id = int(data.split("_", 1)[1])
        target = game.players.get(target_id)
        if not target or not target.alive:
            await query.answer("هذا اللاعب ما تگدر تختاره هسة.", show_alert=True)
            return
        if target_id == user.id and game.last_protected == user.id:
            await query.answer("ما تگدر تحمي نفسك ليلتين ورا بعض يمعود.", show_alert=True)
            return
        for p in game.players.values():
            p.protected_by_healer = False
        target.protected_by_healer = True
        game.last_protected = target_id
        await query.edit_message_text(f"✅ حميت {target.name} هالليلة! 🛡️")
        await send_effect(context.bot, user.id, "healer_save.mp4", f"🛡️ حميت {target.name} بنجاح!")

    elif data.startswith("seer_"):
        if player.role != "seer" or game.phase != GamePhase.SEER:
            await query.answer("هسة مو دور العرّاف.", show_alert=True)
            return
        target_id = int(data.split("_", 1)[1])
        target = game.players.get(target_id)
        if not target or not target.alive or target_id == user.id:
            await query.answer("هذا اللاعب ما تگدر تختاره هسة.", show_alert=True)
            return
        result = "🐺 *ذيب!*" if target.role == "wolf" else "🛡️ *مو ذيب*"
        comments = [
            "صح عليك! كشفته 😂👁️",
            "هاي النتيجة، لا تفضح روحك 😂🤫",
            "خوش كشف يمعود 😂",
        ]
        await query.edit_message_text(
            MSG["seer_result"].format(name=target.name, result=result, comment=random.choice(comments)),
            parse_mode="Markdown"
        )
        await send_effect(context.bot, user.id, "seer_check.mp4", f"🔮 نتيجة الكشف: {target.name}")

    elif data.startswith("kill_"):
        if player.role != "wolf" or game.phase != GamePhase.WOLF:
            await query.answer("هسة مو دور الذيب.", show_alert=True)
            return
        target_id = int(data.split("_", 1)[1])
        target = game.players.get(target_id)
        if not target or not target.alive or target.role == "wolf":
            await query.answer("ما تگدر تختار هذا يمعود.", show_alert=True)
            return
        player._vote_target = target_id
        await query.edit_message_text(f"✅ اخترت {target.name}، خوش اختيار 😂🐺")

    elif data.startswith("lawyer_"):
        if player.role != "lawyer" or game.phase != GamePhase.VOTING:
            await query.answer("هسة مو دور المحامي.", show_alert=True)
            return
        if player.has_used_lawyer:
            await query.answer("دفاعك مستعمله من قبل يمعود.", show_alert=True)
            return
        target_id = int(data.split("_", 1)[1])
        target = game.players.get(target_id)
        if not target or not target.alive:
            await query.answer("هذا اللاعب ما تگدر تختاره هسة.", show_alert=True)
            return
        player._protect_target = target_id
        await query.edit_message_text(f"⚖️ اخترت تدافع عن {target.name} إذا طلع بالتصويت.")
        await send_effect(context.bot, user.id, "lawyer_defense.mp4", f"⚖️ جهزت دفاعك عن {target.name}!")

    elif data.startswith("vote_"):
        if game.phase != GamePhase.VOTING:
            await query.answer("هسة مو وقت التصويت يمعود.", show_alert=True)
            return
        if data == "vote_skip":
            if user.id in game.votes:
                await query.answer("إنت مصوّت من قبل.", show_alert=True)
                return
            game.votes[user.id] = "skip"
            await query.edit_message_text("🚫 قررت تسحب هالمرة.")
            return
        target_id = int(data.split("_", 1)[1])
        target = game.players.get(target_id)
        if not target or not target.alive:
            await query.answer("هذا اللاعب ما تگدر تختاره هسة.", show_alert=True)
            return
        if user.id in game.votes:
            await query.answer("إنت مصوّت من قبل يمعود 😂", show_alert=True)
            return
        game.votes[user.id] = target_id
        player_stats.setdefault(user.id, {"games": 0, "wins": 0, "losses": 0, "votes": 0})["votes"] += 1
        await query.edit_message_text(MSG["vote_cast"])

        # الإعلان ينرسل فوراً بالمجموعة ويكون ويا منشن للطرفين، بدون قائمة مصوتين بالنهاية.
        voter_name = html.escape(player.name)
        target_name = html.escape(target.name)
        voter_mention = f'<a href="tg://user?id={user.id}">{voter_name}</a>'
        target_mention = f'<a href="tg://user?id={target.user_id}">{target_name}</a>'
        await context.bot.send_message(
            chat_id=game.chat_id,
            text=f"🗳️ {voter_mention} صوّت على {target_mention}",
            parse_mode="HTML"
        )



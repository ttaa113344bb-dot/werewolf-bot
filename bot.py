async def process_night_results(update: Update, context: ContextTypes.DEFAULT_TYPE, game: GameSession):
    """Process the results of the night phase"""
    bot = context.bot
    chat_id = update.effective_chat.id
    death_lines = []
    
    # Count wolf votes
    wolf_votes = {}
    for uid, player in game.players.items():
        if player.role == "wolf" and player.alive and hasattr(player, '_vote_target'):
            target = player._vote_target
            wolf_votes[target] = wolf_votes.get(target, 0) + 1
    
    # Pick the target with most votes
    if wolf_votes:
        max_votes = max(wolf_votes.values())
        top_targets = [t for t, v in wolf_votes.items() if v == max_votes]
        chosen_target = random.choice(top_targets)
        
        target_player = game.players.get(chosen_target)
        if target_player and target_player.alive:
            if not target_player.protected_by_healer:
                target_player.alive = False
                game.night_kills.append(chosen_target)
                
                death_lines.append(await build_death_scene(
                    game, "wolf_kill_scene", target_player.name, ROLES[target_player.role]["name"]
                ))
            else:
                death_lines.append(f"الحمدلله! {target_player.name} نجا بفضل الحكيم! 🛡️")
    else:
        # No votes, random target
        alive_non_wolves = [uid for uid, p in game.players.items() if p.alive and p.role != "wolf"]
        if alive_non_wolves:
            chosen = random.choice(alive_non_wolves)
            target_player = game.players[chosen]
            if not target_player.protected_by_healer:
                target_player.alive = False
                game.night_kills.append(chosen)
                death_lines.append(await build_death_scene(
                    game, "wolf_kill_scene", target_player.name, ROLES[target_player.role]["name"]
                ))
    
    # Serial killer strikes - bypasses healer protection entirely
    for uid, player in game.players.items():
        if player.role == "serial_killer" and player.alive and hasattr(player, "_sk_target"):
            target = game.players.get(player._sk_target)
            if target and target.alive:
                target.alive = False
                game.night_kills.append(target.user_id)
                death_lines.append(await build_death_scene(
                    game, "sk_kill_scene", target.name, ROLES[target.role]["name"]
                ))
                await send_serial_killer_effect(bot, chat_id)
    
    # Arsonist ignition - burns everyone doused so far, also bypasses protection
    for uid, player in game.players.items():
        if player.role == "arsonist" and player.alive and getattr(player, "_ignite_now", False):
            burned_any = False
            for tid in list(game.arsonist_doused):
                target = game.players.get(tid)
                if target and target.alive:
                    target.alive = False
                    game.night_kills.append(target.user_id)
                    death_lines.append(await build_death_scene(
                        game, "arsonist_kill_scene", target.name, ROLES[target.role]["name"]
                    ))
                    burned_any = True
            game.arsonist_doused.clear()
            if burned_any:
                await send_arsonist_burn_effect(bot, chat_id)
    
    death_msg = "\n\n".join(death_lines) if death_lines else None
    
    # Announce morning
    if death_msg:
        try:
            await bot.send_message(
                chat_id=chat_id,
                text=MSG["morning_arrives"].format(
                    death_message=death_msg,
                    alive_count=sum(1 for p in game.players.values() if p.alive),
                    alive_list=get_player_list_text({k: v for k, v in game.players.items() if v.alive}),
                    discussion_prompt="💬 *هسة وقت الحچي!* منو تشكون بيه؟"
                ),
                parse_mode="Markdown"
            )
        except:
            pass
    else:
        try:
            await bot.send_message(
                chat_id=chat_id,
                text=MSG["no_death"].format(
                    alive_count=sum(1 for p in game.players.values() if p.alive),
                    alive_list=get_player_list_text({k: v for k, v in game.players.items() if v.alive})
                ),
                parse_mode="Markdown"
            )
        except:
            pass
    
    # Check win condition
    if await check_win(update, context, game):
        return
    
    # Move to discussion
    await discussion_phase(update, context, game)


async def discussion_phase(update: Update, context: ContextTypes.DEFAULT_TYPE, game: GameSession):
    """مناقشة رواية تفاعلية: تنوع حسب وضع الجولة وما تعيد كلام سابق."""
    game.phase = GamePhase.DISCUSSION
    chat_id = game.chat_id or update.effective_chat.id
    opening = narrator_pick(game, "discussion_open")
    await context.bot.send_message(
        chat_id=chat_id,
        text=MSG["discussion_time"].format(seconds=60) + (f"\n\n{opening}" if opening else ""),
        parse_mode="Markdown"
    )

    # تدخلات متفرقة: بالبداية، حسب أحداث الجولة، وبنهاية الوقت.
    elapsed = 0
    checkpoints = [random.randint(8, 12), random.randint(10, 15), random.randint(10, 15), random.randint(8, 12)]
    for idx, delay in enumerate(checkpoints):
        if game.phase != GamePhase.DISCUSSION:
            return
        delay = min(delay, max(0, 55 - elapsed))
        if delay <= 0:
            break
        await asyncio.sleep(delay)
        elapsed += delay
        if game.phase != GamePhase.DISCUSSION:
            return
        if idx == 0 and game.night_kills:
            category = "after_death"
        elif idx == 0 and not game.night_kills:
            category = "after_save"
        elif elapsed >= 35:
            category = "late_discussion"
        else:
            category = "discussion_nudge"
        line = narrator_pick(game, category)
        if line:
            try:
                await context.bot.send_message(chat_id=chat_id, text=line)
            except Exception:
                logger.exception("Could not send discussion narration")

    remaining = max(0, 60 - elapsed)
    if remaining and game.phase == GamePhase.DISCUSSION:
        await asyncio.sleep(remaining)
    if game.phase == GamePhase.DISCUSSION:
        await voting_phase(update, context, game)



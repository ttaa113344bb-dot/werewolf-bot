async def join_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Join an existing game — scoped to the chat /join was sent in, so
    multiple groups running the bot at once never collide into one game."""
    user = update.effective_user
    chat_id = update.effective_chat.id
    
    if not games:
        await update.message.reply_text(MSG["no_game"])
        return
    
    # Only consider a waiting game that belongs to THIS chat
    available_game = None
    for gid, g in games.items():
        if g.phase == GamePhase.WAITING and g.chat_id == chat_id:
            available_game = g
            break
    
    if not available_game:
        await update.message.reply_text(MSG["no_game"])
        return
    
    # Check if already joined
    if user.id in available_game.players:
        await update.message.reply_text(
            MSG["already_joined"].format(name=user.first_name)
        )
        return
    
    # Check if game is full
    if len(available_game.players) >= 20:
        await update.message.reply_text(MSG["game_full"])
        return
    
    # Add player
    available_game.players[user.id] = Player(
        user_id=user.id,
        name=user.first_name
    )
    user_games[user.id] = available_game.game_id
    
    players_text = get_player_list_text(available_game.players)
    
    hint = ""
    if len(available_game.players) >= 5:
        hint = f"✅ العدد صار كافي! صاحب اللعبة يگدر يبدي بـ /startgame"
    else:
        remaining = 5 - len(available_game.players)
        hint = f"⏳ بعد ناقص {remaining} حتى نبدي"
    
    await update.message.reply_text(
        MSG["joined"].format(
            name=user.first_name,
            count=len(available_game.players),
            max=20,
            players_list=players_text,
            hint=hint
        ),
        parse_mode="Markdown"
    )



async def join_timer(application: Application, game_id: str):
    while True:
        game = games.get(game_id)
        if not game or game.phase != GamePhase.WAITING or game.join_deadline is None:
            return
        remaining = game.join_deadline - time.monotonic()
        if remaining <= 0:
            await application.bot.send_message(
                chat_id=game.chat_id,
                text="⏰ خلص وقت الانضمام! صاحب اللعبة يگدر يبدي بـ /startgame إذا العدد صار 5 أو أكثر."
            )
            return
        await asyncio.sleep(min(remaining, 2))



async def process_votes(update: Update, context: ContextTypes.DEFAULT_TYPE, game: GameSession):
    """Process voting results"""
    chat_id = update.effective_chat.id
    
    if not game.votes:
        await context.bot.send_message(
            chat_id=chat_id,
            text="🤷 ماكو أصوات، نروح لليل الجاي...",
            parse_mode="Markdown"
        )
        # Next night
        await night_phase(update, context, game)
        return
    
    # Count votes
    vote_counts = {}
    for voter, target in game.votes.items():
        if target == "skip":
            continue
        vote_counts[target] = vote_counts.get(target, 0) + 1

    # كشف النتيجة الكاملة هسة بس - التصويت كان سري لين هالحظة.
    if vote_counts:
        reveal_lines = ["🗳️ *نتيجة التصويت السري:*\n"]
        for tid, count in sorted(vote_counts.items(), key=lambda kv: kv[1], reverse=True):
            tp = game.players.get(tid)
            name = tp.name if tp else "؟"
            reveal_lines.append(f"• {name}: {count} صوت")
        skip_count = sum(1 for t in game.votes.values() if t == "skip")
        if skip_count:
            reveal_lines.append(f"• 🚫 سحبوا: {skip_count}")
        await context.bot.send_message(
            chat_id=chat_id,
            text="\n".join(reveal_lines),
            parse_mode="Markdown"
        )
    
    if not vote_counts:
        await context.bot.send_message(
            chat_id=chat_id,
            text="🤷 الكل سحب، نروح لليل الجاي...",
            parse_mode="Markdown"
        )
        await night_phase(update, context, game)
        return
    
    max_votes = max(vote_counts.values())
    top_voted = [t for t, v in vote_counts.items() if v == max_votes]
    
    if len(top_voted) > 1:
        # Tie
        names = ", ".join([game.players.get(int(tid), Player(0, "Unknown")).name for tid in top_voted])
        await context.bot.send_message(
            chat_id=chat_id,
            text=MSG["tie_vote"].format(names=names),
            parse_mode="Markdown"
        )
        # Next night without elimination
        await night_phase(update, context, game)
        return
    
    # Eliminate the top voted
    eliminated_id = int(top_voted[0])
    eliminated = game.players.get(eliminated_id)
    
    if eliminated:
        lawyers = [p for p in game.players.values() if p.role == "lawyer" and p.alive and not p.has_used_lawyer]
        defender = next(
            (lawyer for lawyer in lawyers
             if hasattr(lawyer, "_protect_target") and lawyer._protect_target == eliminated_id),
            None
        )
        if defender:
            defender.has_used_lawyer = True
            defense_line = narrator_pick(game, "lawyer_defense_win") or f"⚖️ *المحامي دافع عن {eliminated.name}!*\n\nهالمرة ما راح يطلع 😎"
            defense_line = defense_line.format(name=eliminated.name) if "{name}" in defense_line else defense_line
            await context.bot.send_message(
                chat_id=chat_id,
                text=defense_line,
                parse_mode="Markdown"
            )
            await send_effect(context.bot, defender.user_id, "lawyer_defense.mp4", f"⚖️ دفاعك نجح وأنقذت {eliminated.name}!")
            await send_effect(context.bot, eliminated_id, "lawyer_defense.mp4", "🛡️ المحامي أنقذك من الطرد!")
            game.round_num += 1
            await night_phase(update, context, game)
            return

        eliminated.alive = False

        # 🕯️ آخر كلمة: نفتح نافذة 15 ثانية للمطرود يحچي قبل ما دوره ينكشف.
        LAST_WORDS_WINDOW[chat_id] = eliminated.user_id
        await context.bot.send_message(
            chat_id=chat_id,
            text=f"🤫 *سكتوا الكل...* {eliminated.name}، هذا وقتك الأخير تحچي (15 ثانية) 🕯️",
            parse_mode="Markdown"
        )
        await asyncio.sleep(15)
        LAST_WORDS_WINDOW.pop(chat_id, None)

        comments = [
            "خلصت سالفتك يمعود 😂",
            "يلا الله وياك 😂",
            "والله چنت شاك بيك 😂",
        ]
        
        # فيديو السكين مخصص للسفاح فقط، لذلك ما نستخدمه بالإقصاء العادي.
        await context.bot.send_message(
            chat_id=chat_id,
            text=MSG["elimination_result"].format(
                accused_name=eliminated.name,
                eliminated_message=MSG["player_eliminated"].format(
                    name=eliminated.name,
                    role=ROLES[eliminated.role]["name"],
                    comment=random.choice(comments)
                )
            ),
            parse_mode="Markdown"
        )

        # 🤡 الأخرق: لو انطرد بالتصويت (مو بالليل)، يفوز فورًا وتخلص اللعبة هنا.
        if eliminated.role == "fool":
            await context.bot.send_message(
                chat_id=chat_id,
                text=MSG["fool_win"].format(name=eliminated.name),
                parse_mode="Markdown"
            )
            await send_effect(context.bot, chat_id, "outcast_win.mp4", f"🤡 {eliminated.name} خدعكم كلكم!")
            for _uid, _p in game.players.items():
                if _uid == eliminated.user_id:
                    await asyncio.to_thread(db_bump, _uid, _p.name, 0, 1, 0, 0)
                else:
                    await asyncio.to_thread(db_bump, _uid, _p.name, 0, 0, 1, 0)
            game.phase = GamePhase.ENDED
            return

        # 💣 البداغ: لو انطرد بالتصويت، يفجّر لاعب عشوائي ثاني وياه.
        if eliminated.role == "bomber":
            other_alive = [p for p in game.players.values() if p.alive and p.user_id != eliminated.user_id]
            if other_alive:
                victim = random.choice(other_alive)
                victim.alive = False
                await context.bot.send_message(
                    chat_id=chat_id,
                    text=MSG["bomb_explosion"].format(bomber=eliminated.name, victim=victim.name),
                    parse_mode="Markdown"
                )
                await send_effect(context.bot, chat_id, "wolf_victory.mp4", f"💣 {victim.name} انفجر وياه!")
    
    # Check win condition
    if await check_win(update, context, game):
        return
    
    # Next round - night
    game.round_num += 1
    await night_phase(update, context, game)


async def check_win(update: Update, context: ContextTypes.DEFAULT_TYPE, game: GameSession) -> bool:
    """Check if any team has won"""
    chat_id = update.effective_chat.id
    
    alive_wolves = [p for p in game.players.values() if p.alive and p.team == "wolves"]
    alive_village = [p for p in game.players.values() if p.alive and p.team == "village"]
    total_alive = sum(1 for p in game.players.values() if p.alive)

    # Solo teams (outcast, serial killer, arsonist) each win if they're the
    # only team left standing - checked before wolves/village.
    solo_teams = {
        "outcast": ("outcast_win", "outcast_win.mp4", "🃏 {name} فاز وحده!"),
        "serial_killer": ("serial_killer_win", "serial_killer_attack.mp4", "🔪 {name} فاز وحده!"),
        "arsonist": ("arsonist_win", "arsonist_burn.mp4", "🔥 {name} فاز وحده!"),
    }
    for team_key, (msg_key, media_file, caption_tpl) in solo_teams.items():
        alive_solo = [p for p in game.players.values() if p.alive and p.team == team_key]
        if alive_solo and len(alive_solo) == total_alive:
            name = alive_solo[0].name
            await context.bot.send_message(
                chat_id=chat_id,
                text=MSG[msg_key].format(name=name),
                parse_mode="Markdown"
            )
            await send_effect(context.bot, chat_id, media_file, caption_tpl.format(name=name))
            await record_game_result(game, team_key)
            game.phase = GamePhase.ENDED
            return True

    solo_alive_any = any(
        p.alive and p.team in ("outcast", "serial_killer", "arsonist")
        for p in game.players.values()
    )
    wolves_win = (not solo_alive_any) and len(alive_wolves) >= len(alive_village) and len(alive_village) > 0
    village_win = (not solo_alive_any) and len(alive_wolves) == 0 and len(alive_village) > 0

    if wolves_win:
        wolves_list = "\n".join([f"🐺 {p.name}" for p in game.players.values() if p.role == "wolf"])
        await context.bot.send_message(
            chat_id=chat_id,
            text=MSG["wolves_win"].format(
                wolves_list=wolves_list,
                taunt=get_random_taunt(MSG["wolf_taunts"])
            ),
            parse_mode="Markdown"
        )
        await send_random_effect(context.bot, chat_id, ["wolf_victory.mp4", "wolf_victory_alt.mp4"], "🐺🩸 الذئاب فازوا!")
        await record_game_result(game, "wolves")
        game.phase = GamePhase.ENDED
        return True
    
    if village_win:
        survivors = [p for p in game.players.values() if p.alive]
        survivors_list = "\n".join([f"🛡️ {p.name}" for p in survivors])
        await context.bot.send_message(
            chat_id=chat_id,
            text=MSG["village_win"].format(
                survivors_list=survivors_list,
                celebration=get_random_taunt(MSG["village_celebrations"])
            ),
            parse_mode="Markdown"
        )
        await send_effect(context.bot, chat_id, "village_win.mp4", "🏆🎉 أهل القرية فازوا!")
        await record_game_result(game, "village")
        game.phase = GamePhase.ENDED
        return True
    
    return False


async def endgame_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """End the current game"""
    user = update.effective_user
    
    if user.id not in user_games or user_games[user.id] not in games:
        await update.message.reply_text(MSG["no_game"])
        return
    
    game = games[user_games[user.id]]
    
    if user.id != game.host_id:
        await update.message.reply_text(MSG["not_host"].format(name=user.first_name))
        return
    
    game.phase = GamePhase.ENDED
    await update.message.reply_text(MSG["game_ended"])



def narrator_pick(game: GameSession, category: str):
    options = NARRATION_BANK.get(category, [])
    unused = [x for x in options if x not in game.narration_used and x not in USED_NARRATION]
    if not unused:
        unused = [x for x in options if x not in game.narration_used] or options
    if not unused:
        return None
    line = random.choice(unused)
    game.narration_used.add(line)
    USED_NARRATION.add(line)
    save_used_narration(USED_NARRATION)
    return line

async def build_death_scene(game: GameSession, category: str, name: str, role_name: str) -> str:
    """يبني مشهد موت: يجرب الذكاء الاصطناعي أول (لو مفعّل)، وإلا يرجع لبنك
    الجمل الثابت المختبر (بلا تكرار)، وبعدين يكشف الدور تحت المشهد."""
    ai_scene = await ai_death_scene(name, category)
    if ai_scene:
        return f"💀 *{ai_scene}*\n\n_الدور: {role_name}_"

    scene = narrator_pick(game, category)
    if not scene:
        scene = "{name} انلگى ميت بالصبح، وماكو تفاصيل زيادة. 💀"
    scene = scene.format(name=f"*{name}*")
    return f"💀 {scene}\n\n_الدور: {role_name}_"


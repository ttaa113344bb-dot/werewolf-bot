async def send_effect(bot, chat_id: int, filename: str, caption: str = None):
    """Send a short local MP4 effect; silently fall back if the media is unavailable."""
    path = os.path.join(MEDIA_DIR, filename)
    if not os.path.isfile(path):
        return False
    try:
        with open(path, "rb") as video:
            await bot.send_video(
                chat_id=chat_id,
                video=video,
                caption=caption,
                supports_streaming=True,
                width=480,
                height=640,
            )
        return True
    except Exception as exc:
        logger.warning("Could not send effect %s to %s: %s", filename, chat_id, exc)
        return False

async def send_random_effect(bot, chat_id: int, filenames, caption: str = None):
    """Pick one local effect at random from the supplied event-specific files."""
    available = [name for name in filenames if os.path.isfile(os.path.join(MEDIA_DIR, name))]
    if not available:
        return False
    return await send_effect(bot, chat_id, random.choice(available), caption)



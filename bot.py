async def startgame_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Start the game (host only)"""
    user = update.effective_user
    
    if user.id not in user_games or user_games[user.id] not in games:
        await update.message.reply_text(MSG["no_game"])
        return
    
    game = games[user_games[user.id]]
    
    # Check if host
    if user.id != game.host_id:
        await update.message.reply_text(MSG["not_host"].format(name=user.first_name))
        return
    
    # Check minimum players
    if len(game.players) < 5:
        await update.message.reply_text(
            f"⛔ بعد ناقص لاعبين! نحتاج 5، وإنتو هسة {len(game.players)}"
        )
        return
    
    # سجّل بداية اللعبة بالإحصائيات
    for _uid in game.players:
        player_stats.setdefault(_uid, {"games": 0, "wins": 0, "losses": 0, "votes": 0})["games"] += 1

    # Assign roles
    roles = assign_roles(len(game.players))
    if not roles:
        await update.message.reply_text("صار لخبطه بتوزيع الأدوار، جرّب مرة ثانية.")
        return
    
    for i, (uid, player) in enumerate(game.players.items()):
        player.role = roles[i]
        player.team = ROLES[roles[i]]["team"]
    
    # Start the game
    game.phase = GamePhase.NIGHT
    game.round_num = 1
    
    # بداية اللعبة: فيديو القمر فقط، بدون حريق أو سكين.
    await send_effect(
        context.bot,
        update.effective_chat.id,
        EVENT_EFFECTS["game_start"],
        "🌙 عصام @eia_qw"
    )
    await update.message.reply_text("🐺 *عصام @eia_qw*", parse_mode="Markdown")
    await update.message.reply_text(MSG["game_starting"], parse_mode="Markdown")
    
    # Send roles to each player via PM
    bot = context.bot
    for uid, player in game.players.items():
        role_info = ROLES[player.role]
        try:
            await bot.send_message(
                chat_id=uid,
                text=MSG["role_assigned"].format(
                    role_name=role_info["name"],
                    role_description=role_info["description"],
                    abilities=f"*قدراتك:*\n{role_info['abilities']}"
                ),
                parse_mode="Markdown"
            )
        except Exception as e:
            logger.warning(f"Could not PM role to {uid}: {e}")
            # If can't PM, announce in group (less ideal but works)
            pass
    
    # Start night phase
    await asyncio.sleep(3)
    await night_phase(update, context, game)



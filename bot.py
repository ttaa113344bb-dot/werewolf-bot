async def announce_join(bot, game: GameSession, user):
    safe_name = html.escape(user.first_name or "لاعب")
    mention = f'<a href="tg://user?id={user.id}">{safe_name}</a>'
    await bot.send_message(
        chat_id=game.chat_id,
        text=f"🐺 أفلا انضم {mention} للعبة!",
        parse_mode="HTML"
    )


def add_player_to_game(game: GameSession, user):
    if user.id in game.players:
        return "already"
    if len(game.players) >= 20:
        return "full"
    game.players[user.id] = Player(user_id=user.id, name=user.first_name or "لاعب")
    user_games[user.id] = game.game_id
    return "joined"


async def join_from_deep_link(update: Update, context: ContextTypes.DEFAULT_TYPE, game_id: str):
    user = update.effective_user
    game = games.get(game_id)
    if not game or game.phase != GamePhase.WAITING:
        await update.message.reply_text("هاللعبة ما بقت مفتوحة يمعود.")
        return
    status = add_player_to_game(game, user)
    if status == "already":
        await update.message.reply_text("إنت داخل من قبل يمعود 😂")
        return
    if status == "full":
        await update.message.reply_text("اللعبة امتلت يمعود 😂")
        return
    chat_title = game.host_name
    try:
        chat = await context.bot.get_chat(game.chat_id)
        chat_title = chat.title or game.host_name
    except Exception:
        pass
    await update.message.reply_text(f"🐺 تم انضمامك بكروب «{chat_title}» بنجاح 😎")
    await announce_join(context.bot, game, user)


async def start_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Handle /start and private deep-link joining."""
    if context.args and context.args[0].startswith("join_"):
        game_id = context.args[0].split("_", 1)[1]
        await join_from_deep_link(update, context, game_id)
        return
    await update.message.reply_text(MSG["welcome"], parse_mode="Markdown")


async def newgame_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Create a new game session"""
    user = update.effective_user
    chat_id = update.effective_chat.id
    
    # Check if user already has an active game
    if user.id in user_games and user_games[user.id] in games:
        old_game = games[user_games[user.id]]
        if old_game.phase != GamePhase.ENDED:
            await update.message.reply_text(
                "يا {name}، عندك لعبة شغالة! إذا تريد تنهيها اكتب /endgame.".format(name=user.first_name)
            )
            return
    
    game_id = generate_game_id()
    game = GameSession(
        game_id=game_id,
        host_id=user.id,
        host_name=user.first_name,
        chat_id=chat_id
    )
    
    # Add host as first player
    game.players[user.id] = Player(
        user_id=user.id,
        name=user.first_name
    )
    
    games[game_id] = game
    user_games[user.id] = game_id

    for subscriber_id in list(nextgame_subscribers):
        try:
            await context.bot.send_message(chat_id=subscriber_id, text="🐺 يمعود، انفتحت لعبة جديدة! روح للكروب إذا تريد تلعب.")
        except Exception:
            pass
    nextgame_subscribers.clear()

    players_text = get_player_list_text(game.players)
    join_seconds = 60
    game.join_deadline = time.monotonic() + join_seconds
